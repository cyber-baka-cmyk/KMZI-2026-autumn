inline void S(uint8_t s[64]) { for (int i = 0; i < 64; ++i) s[i] = Pi[s[i]]; }
inline void P(uint8_t s[64]) {
    uint8_t t[64]; for (int i = 0; i < 64; ++i) t[i] = s[Tau[i]];
    std::memcpy(s, t, 64);
}
inline void L(uint8_t s[64]) {
    for (int i = 0; i < 8; ++i) {
        uint64_t v = 0;
        for (int j = 0; j < 8; ++j) v = (v << 8) | s[i*8 + j];
        uint64_t r = 0;
        for (int j = 0; j < 64; ++j)
            if ((v >> (63 - j)) & 1) r ^= A[j];
        for (int j = 0; j < 8; ++j) s[i*8 + j] = (uint8_t)(r >> (56 - 8*j));
    }
}
inline void LPS(uint8_t s[64]) { S(s); P(s); L(s); }

inline void g(uint8_t h[64], const uint8_t N[64], const uint8_t m[64]) {
    uint8_t K[64], state[64], t[64];
    for (int i = 0; i < 64; ++i) t[i] = h[i] ^ N[i];
    LPS(t);
    std::memcpy(K, t, 64);
    std::memcpy(state, m, 64);
    for (int r = 0; r < 12; ++r) {
        for (int i = 0; i < 64; ++i) t[i] = K[i] ^ C[r][i];
        LPS(t);
        std::memcpy(K, t, 64);
        for (int i = 0; i < 64; ++i) t[i] = state[i] ^ K[i];
        LPS(t);
        std::memcpy(state, t, 64);
    }
    for (int i = 0; i < 64; ++i) h[i] ^= state[i] ^ m[i];
}

inline void add512(uint8_t a[64], const uint8_t b[64]) {
    unsigned carry = 0;
    for (int i = 0; i < 64; ++i) {
        unsigned s = a[i] + b[i] + carry;
        a[i] = (uint8_t)s;
        carry = s >> 8;
    }
}
inline void add512_u64(uint8_t a[64], uint64_t v) {
    uint8_t b[64]; std::memset(b, 0, 64);
    for (int i = 0; i < 8; ++i) { b[i] = (uint8_t)v; v >>= 8; }
    add512(a, b);
}

inline void hash512(const uint8_t* msg, size_t len, uint8_t out[64]) {
    uint8_t h[64], N[64], Sigma[64], block[64];
    std::memset(h, 0x01, 64);
    std::memset(N, 0, 64);
    std::memset(Sigma, 0, 64);

    size_t full = len / 64;
    for (size_t i = 0; i < full; ++i) {
        g(h, N, msg + i*64);
        add512_u64(N, 512);
        add512(Sigma, msg + i*64);
    }
    size_t rem = len % 64;
    std::memset(block, 0, 64);
    if (rem) std::memcpy(block, msg + full*64, rem);
    block[rem] = 0x01;
    g(h, N, block);
    add512_u64(N, (uint64_t)rem * 8);
    add512(Sigma, block);

    uint8_t zero[64]; std::memset(zero, 0, 64);
    g(h, zero, N);
    g(h, zero, Sigma);
    std::memcpy(out, h, 64);
}


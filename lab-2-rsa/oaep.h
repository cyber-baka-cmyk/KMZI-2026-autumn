constexpr size_t HASH_LEN = 64;   // Стрибог-512
constexpr size_t MAX_K    = 512;  // 4096 бит
constexpr size_t MAX_DB   = MAX_K - HASH_LEN - 1;  // 447
constexpr size_t MAX_M    = MAX_DB - HASH_LEN - 1; // 382

inline uint32_t ct_eq_u32(uint32_t a, uint32_t b) {
    uint32_t x = a ^ b;
    return 1u - ((x | (0u - x)) >> 31);
}
inline uint32_t ct_lt_u32(uint32_t a, uint32_t b) {
    return ((a - b) >> 31) & 1u;
}

inline void mgf1(const uint8_t* Z, size_t zlen, uint8_t* out, size_t outlen) {
    uint8_t buf[512 + 4];
    uint8_t h[64];
    size_t off = 0;
    uint32_t counter = 0;
    while (off < outlen) {
        std::memcpy(buf, Z, zlen);
        buf[zlen+0] = (uint8_t)(counter >> 24);
        buf[zlen+1] = (uint8_t)(counter >> 16);
        buf[zlen+2] = (uint8_t)(counter >> 8);
        buf[zlen+3] = (uint8_t)(counter);
        streebog::hash512(buf, zlen + 4, h);
        size_t copy = (outlen - off < 64) ? (outlen - off) : 64;
        std::memcpy(out + off, h, copy);
        off += copy;
        ++counter;
    }
}

inline int oaep_encode(const uint8_t* msg, size_t msg_len, size_t k,
                       const uint8_t* label, size_t label_len,
                       const uint8_t* seed, uint8_t* em) {
    if (k > MAX_K) return -1;
    if (msg_len > k - 2*HASH_LEN - 2) return -2;

    uint8_t lHash[HASH_LEN];
    streebog::hash512(label, label_len, lHash);

    size_t dbLen = k - HASH_LEN - 1;
    size_t psLen = dbLen - HASH_LEN - 1 - msg_len;

    uint8_t DB[MAX_DB];
    std::memcpy(DB, lHash, HASH_LEN);
    std::memset(DB + HASH_LEN, 0, psLen);
    DB[HASH_LEN + psLen] = 0x01;
    if (msg_len) std::memcpy(DB + HASH_LEN + psLen + 1, msg, msg_len);

    uint8_t dbMask[MAX_DB];
    mgf1(seed, HASH_LEN, dbMask, dbLen);

    uint8_t maskedDB[MAX_DB];
    for (size_t i = 0; i < dbLen; ++i) maskedDB[i] = DB[i] ^ dbMask[i];

    uint8_t seedMask[HASH_LEN];
    mgf1(maskedDB, dbLen, seedMask, HASH_LEN);

    uint8_t maskedSeed[HASH_LEN];
    for (size_t i = 0; i < HASH_LEN; ++i) maskedSeed[i] = seed[i] ^ seedMask[i];

    em[0] = 0x00;
    std::memcpy(em + 1, maskedSeed, HASH_LEN);
    std::memcpy(em + 1 + HASH_LEN, maskedDB, dbLen);
    return 0;
}

inline int oaep_decode(const uint8_t* em, size_t k,
                       const uint8_t* label, size_t label_len,
                       uint8_t* msg, size_t* msg_len) {
    if (k > MAX_K) return -1;

    uint8_t lHash[HASH_LEN];
    streebog::hash512(label, label_len, lHash);

    size_t dbLen = k - HASH_LEN - 1;

    uint8_t maskedSeed[HASH_LEN];
    uint8_t maskedDB[MAX_DB];
    std::memcpy(maskedSeed, em + 1, HASH_LEN);
    std::memcpy(maskedDB, em + 1 + HASH_LEN, dbLen);

    uint8_t seedMask[HASH_LEN];
    mgf1(maskedDB, dbLen, seedMask, HASH_LEN);

    uint8_t seed[HASH_LEN];
    for (size_t i = 0; i < HASH_LEN; ++i) seed[i] = maskedSeed[i] ^ seedMask[i];

    uint8_t dbMask[MAX_DB];
    mgf1(seed, HASH_LEN, dbMask, dbLen);

    uint8_t DB[MAX_DB];
    for (size_t i = 0; i < dbLen; ++i) DB[i] = maskedDB[i] ^ dbMask[i];

    uint32_t err = em[0];
    for (size_t i = 0; i < HASH_LEN; ++i)
        err |= (uint32_t)(DB[i] ^ lHash[i]);

    uint32_t pos = 0, found = 0, zeros_ok = 1;
    for (size_t i = HASH_LEN; i < dbLen; ++i) {
        uint32_t b = DB[i];
        uint32_t is_zero = ct_eq_u32(b, 0);
        uint32_t is_one  = ct_eq_u32(b, 1);
        uint32_t take = (1u - found) & zeros_ok & is_one;
        pos = pos * (1u - take) + (uint32_t)i * take;
        found |= take;
        zeros_ok = (zeros_ok & is_zero) | found;
    }
    err |= (1u - found);

    uint32_t ok = ct_eq_u32(err, 0);

    uint32_t mlen = (uint32_t)(dbLen - pos - 1) & (0u - ok);
    for (size_t i = 0; i < dbLen; ++i) msg[i] = 0;
    for (size_t i = 0; i < dbLen; ++i) {
        uint32_t src = pos + 1u + (uint32_t)i;
        uint32_t in_range = ct_lt_u32(src, (uint32_t)dbLen);
        uint32_t safe = src & (0u - in_range);
        uint8_t v = DB[safe]; 
        msg[i] = (uint8_t)(v & (uint8_t)(0u - (uint8_t)in_range) & (uint8_t)(0u - (uint8_t)ok));
    }

    *msg_len = mlen;
    return (int)(1u - ok) * (-1);
}

